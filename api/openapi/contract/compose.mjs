// Writes .composed.yaml: admin-api.yaml plus a $ref for every path and every component of common.yaml and of each
// module file. Each root tag names one module file (<tag>.yaml), so module agents add paths and components without
// editing the root, and every component reaches the bundle even before an operation uses it. Redocly lints and
// bundles the composed root. Fails when two files claim the same path or component name, because the bundler would
// silently rename the second component instead.
import { readFileSync, writeFileSync } from 'node:fs'
import { parse, stringify } from 'yaml'

const dir = new URL('.', import.meta.url)
const read = (file) => parse(readFileSync(new URL(file, dir), 'utf8'))
const pointerOf = (path) => encodeURIComponent(path.replaceAll('~', '~0').replaceAll('/', '~1'))

const root = read('admin-api.yaml')
const owners = new Map()
const clashes = []
const claim = (name, file) => {
  if (owners.has(name)) clashes.push(`${name}: ${owners.get(name)}.yaml and ${file}.yaml`)
  else owners.set(name, file)
}

for (const file of ['common', ...root.tags.map((tag) => tag.name)]) {
  const doc = read(`${file}.yaml`)
  for (const path of Object.keys(doc.paths)) {
    claim(`path ${path}`, file)
    root.paths[path] = { $ref: `./${file}.yaml#/paths/${pointerOf(path)}` }
  }
  for (const [section, entries] of Object.entries(doc.components ?? {})) {
    root.components[section] ??= {}
    for (const name of Object.keys(entries)) {
      claim(`components.${section}.${name}`, file)
      root.components[section][name] = { $ref: `./${file}.yaml#/components/${section}/${name}` }
    }
  }
}

if (clashes.length > 0) {
  console.error(`Contract composition failed, names claimed twice:\n  ${clashes.join('\n  ')}`)
  process.exit(1)
}

writeFileSync(new URL('.composed.yaml', dir), `# Generated by compose.mjs from admin-api.yaml and the module files. Do not edit.\n${stringify(root)}`)
